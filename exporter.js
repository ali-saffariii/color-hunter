/*! Color Hunter — text exports
 *
 *  CSS variables, design tokens and SVG swatches, built as plain strings from
 *  plain data. Nothing here touches the DOM or storage, so every format can be
 *  tested in Node and what a designer pastes into their project is exactly what
 *  the tests saw.
 *
 *  Everything that came from a person — a palette name, a colour label — is
 *  turned into a safe identifier or escaped before it goes into a file. Colour
 *  values are only ever six-digit hex strings that were validated on the way in.
 */
(function (root, factory) {
  var isNode = typeof module === 'object' && module.exports;
  var api = factory(isNode ? require('./color-engine.js') : root.CH, isNode ? require('./studio.js') : root.CHStudio);
  if (isNode) module.exports = api;
  root.CHExport = api;
}(typeof globalThis !== 'undefined' ? globalThis : this, function (CH, Studio) {
  'use strict';

  var isHex = function (s) { return typeof s === 'string' && /^#[0-9a-fA-F]{6}$/.test(s); };
  var up = function (s) { return s.toUpperCase(); };

  /* ---------- names ---------- */

  /* An ASCII identifier from anything. Letters from other scripts are dropped
     (a Persian label gives '' and the caller falls back to a numbered name):
     a variable name that only some toolchains accept is worse than a plain one. */
  function slug(s, fallback) {
    var out = String(s === undefined || s === null ? '' : s).normalize('NFKD').replace(/[̀-ͯ]/g, '')
      .toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40);
    return out || fallback || '';
  }

  /* One unique identifier per colour: the label if it makes a usable slug, else
     its position (with `unlabeled` in front when given). Duplicates get a numeric
     suffix, so two colours both labelled "Blue" never share a name. */
  function ids(colors, unlabeled) {
    var used = {}, out = [];
    colors.forEach(function (c, i) {
      var base = slug(c.name, '') || ((unlabeled || '') + (i + 1));
      var n = base, k = 2;
      while (used[n]) n = base + '-' + (k++);
      used[n] = 1;
      out.push(n);
    });
    return out;
  }

  function fileName(title, kind, ext) {
    var base = slug(title, 'color-hunter');
    return base + '-' + kind + '.' + ext;
  }

  /* ---------- value notation ---------- */

  var FORMATS = ['hex', 'rgb', 'hsl', 'oklch'];
  function value(hex, format) {
    var f = Studio.formats(hex);
    return format === 'rgb' ? f.rgb : format === 'hsl' ? f.hsl : format === 'oklch' ? f.oklch : f.hex;
  }
  function comment(s) { return String(s).replace(/\*\//g, '* /').replace(/[\r\n]+/g, ' '); }

  /* ---------- CSS custom properties ---------- */

  /* input: { title, colors:[{h,name}], roles?:{light,dark}, format }
       - plain palette:  :root { --<prefix>-<n>: value; }
       - UI system:      light in :root, dark under both the OS preference and
                         an explicit [data-theme="dark"], so a site can follow
                         the system or let the visitor choose. */
  function cssVariables(input) {
    var format = FORMATS.indexOf(input.format) >= 0 ? input.format : 'hex';
    var head = '/* ' + comment(input.title || 'Palette') + ' — generated by Color Hunter */\n';
    var out = head;
    if (input.roles && (Object.keys(input.roles.light || {}).length || Object.keys(input.roles.dark || {}).length)) {
      var block = function (set, indent) {
        return Object.keys(set).filter(function (k) { return isHex(set[k]); }).map(function (k) {
          return indent + '--' + k.replace(/[A-Z]/g, function (m) { return '-' + m.toLowerCase(); }) + ': ' + value(set[k], format) + ';';
        }).join('\n');
      };
      var light = input.roles.light || {}, dark = input.roles.dark || {};
      out += ':root {\n  color-scheme: light dark;\n' + block(light, '  ') + '\n}\n';
      if (Object.keys(dark).length) {
        out += '\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n' + block(dark, '    ') + '\n  }\n}\n';
        out += '\n:root[data-theme="dark"] {\n' + block(dark, '  ') + '\n}\n';
      }
      return out;
    }
    var colors = (input.colors || []).filter(function (c) { return isHex(c.h); });
    var prefix = slug(input.title, 'color'), keys = ids(colors);
    out += ':root {\n' + colors.map(function (c, i) {
      return '  --' + prefix + '-' + keys[i] + ': ' + value(c.h, format) + ';';
    }).join('\n') + '\n}\n';
    return out;
  }

  /* ---------- design tokens (W3C Design Tokens Community Group format) ---------- */

  /* Values are hex strings, which every current token tool reads. A UI system
     becomes color.light.* and color.dark.* groups; a plain palette becomes
     color.<palette>.<name>. */
  function designTokens(input) {
    var root = { color: {} };
    function token(h, desc) {
      var t = { $value: up(h), $type: 'color' };
      if (desc) t.$description = String(desc).slice(0, 200);
      return t;
    }
    if (input.roles && (Object.keys(input.roles.light || {}).length || Object.keys(input.roles.dark || {}).length)) {
      ['light', 'dark'].forEach(function (mode) {
        var set = input.roles[mode] || {}, group = {};
        Object.keys(set).forEach(function (k) { if (isHex(set[k])) group[k] = token(set[k]); });
        if (Object.keys(group).length) root.color[mode] = group;
      });
    } else {
      var colors = (input.colors || []).filter(function (c) { return isHex(c.h); });
      var group = {}, keys = ids(colors, 'color-');
      colors.forEach(function (c, i) { group[keys[i]] = token(c.h, c.name || ''); });
      root.color[slug(input.title, 'palette')] = group;
    }
    return JSON.stringify(root, null, 2) + '\n';
  }

  /* ---------- SVG swatches ---------- */

  function esc(s) {
    return String(s === undefined || s === null ? '' : s).replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, '')
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  }

  /* A row of labelled swatches. Labels use the readable ink for each colour, and
     the file carries its own title for screen readers. */
  function svgSwatches(input) {
    var colors = (input.colors || []).filter(function (c) { return isHex(c.h); });
    var n = Math.max(colors.length, 1), cols = Math.min(n, 5), rows = Math.ceil(n / cols);
    var cw = 160, ch = 200, gap = 12, pad = 16;
    var W = pad * 2 + cols * cw + (cols - 1) * gap, H = pad * 2 + rows * ch + (rows - 1) * gap;
    var body = colors.map(function (c, i) {
      var x = pad + (i % cols) * (cw + gap), y = pad + Math.floor(i / cols) * (ch + gap);
      var ink = CH.hex(CH.inkOn(CH.h2r(c.h)));
      var label = c.name ? '<text x="' + (x + 12) + '" y="' + (y + ch - 40) + '" font-size="13" fill="' + ink + '" opacity=".85">' + esc(String(c.name).slice(0, 22)) + '</text>' : '';
      return '<g><rect x="' + x + '" y="' + y + '" width="' + cw + '" height="' + ch + '" fill="' + up(c.h) + '"/>' + label +
        '<text x="' + (x + 12) + '" y="' + (y + ch - 14) + '" font-size="16" font-weight="700" fill="' + ink + '">' + up(c.h) + '</text></g>';
    }).join('');
    return '<?xml version="1.0" encoding="UTF-8"?>\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' + W + ' ' + H + '" width="' + W + '" height="' + H + '" font-family="Helvetica, Arial, sans-serif" role="img">' +
      '<title>' + esc(input.title || 'Color swatches') + '</title>' + body + '</svg>\n';
  }

  return {
    slug: slug, ids: ids, fileName: fileName, esc: esc, FORMATS: FORMATS,
    cssVariables: cssVariables, designTokens: designTokens, svgSwatches: svgSwatches
  };
}));
